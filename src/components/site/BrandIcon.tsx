interface BrandIconProps {
  slug: string
  size?: number
  color?: string
  className?: string
}

export default function BrandIcon({
  slug,
  size = 24,
  color,
  className,
}: BrandIconProps) {
  const key = slug.toLowerCase()

  const Packaged = ICON_MAP[key]
  if (Packaged) {
    return <Packaged size={size} color={color} className={className} />
  }

  const custom = CUSTOM_ICONS[key]
  if (custom) {
    const tint = color ?? "currentColor"
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox={custom.viewBox}
        className={className}
        aria-hidden="true"
        focusable="false"
        fill={custom.stroke ? "none" : undefined}
        stroke={custom.stroke ? tint : undefined}
        strokeWidth={custom.stroke ? 18 : undefined}
        strokeLinecap={custom.stroke ? "round" : undefined}
        strokeLinejoin={custom.stroke ? "round" : undefined}
      >
        {custom.paths.map((p, i) => (
          <path
            key={i}
            d={p.d}
            fill={custom.stroke ? "none" : (p.fill ?? tint)}
          />
        ))}
      </svg>
    )
  }

  return null
}
